#!/bin/sh
# Writes the five entry programs from common.part (run from this directory).
SP='stack_policy(0, :keep_last_message), state_policy(:keep_state_area)'
mk() { # name comment spawns refs mode
{
echo "// SD-47 probe, $2 Generated by gen.sh from common.part."
cat common.part
cat <<EOF

fn main() -> int64 {
    sequence proc[concurrency, device_io]
        _: atom <- start_reporter();
        t0: int64 <- monotonic_time();
        x: actor_ref <- spawn(0, idle, $SP);
$3
        _: boolean <- cast(k, { kind: 1, a: b1, b: $4 } impl ActorMessage {});
        _: int64 <- wait_for_exit()
    produces pure 0 end
}
EOF
} > $1.silica
}
TK() { echo "        k: actor_ref <- spawn({ t0: t0, n: 0, last: t0, b1: x, b2: x, mode: $1, spins: spins_default() }, ticker, $SP);"; }
B() { echo "        b$1: actor_ref <- spawn({ t0: t0, id: $1 }, busy, $SP);"; }
mk a_ticker_first "variant a: the ticker is spawned before the busy actor." "$(TK 0)
$(B 1)" x
mk b_busy_first "variant b: the busy actor is spawned before the ticker." "$(B 1)
$(TK 0)" x
mk c_two_busy "variant c: two busy actors start at the same tick." "$(B 1)
$(B 2)
$(TK 2)" b2
mk d_migrate_away "variant d: at tick 1 the ticker migrates itself to a carrier other than the busy actor's." "$(B 1)
$(TK 3)" x
mk e_migrate_onto "variant e: at tick 1 the ticker migrates itself onto the busy actor's carrier." "$(B 1)
$(TK 4)" x
