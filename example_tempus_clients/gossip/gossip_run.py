#!/usr/bin/env python3
"""gossip_run.py: run several instances of the example TEMPUS clients' driver applications on this machine, as one
TEMPUS network, and check that they discover each other by gossip. EXAMPLE ONLY: the keys, certificates and tokens are
TEST ONLY fixtures made from fixed seeds (trials/t5_tempus_tls/certs, tools/bees_tempus_certs.py).

    gossip_run.py run NAME [--timeout SECONDS] [--out DIR]
        NAME    python | kotlin | swift | silica    one sentinel and three edges, all instances of that language's driver
                mixed                               a Silica sentinel and one edge of each language: Silica, Python,
                                                    Kotlin, Swift
                trio                                the mixed network without the Silica driver: a Swift sentinel and
                                                    one edge each of Python, Kotlin and Swift
        Starts the sentinel, then the edges, on 127.0.0.1 (ports: tools/trial_ports.py c7_tempus_gossip). Every edge
        knows only the sentinel's address. Waits until every instance has learned of every edge in its edge store,
        every edge has learned of the sentinel in its sentinel store, and every instance has merged a shuffle of its
        edge store (at least MIN_SECONDS, at most the timeout), then stops them. Each instance's own output is written
        to DIR/NAME.LABEL.out (it depends on timing and on random draws, so it is not compared with anything); the
        check, which is the same on every run, is written to DIR/NAME.check and printed. Exit 0 when every line of
        the check that ends in a verdict says yes, 1 otherwise.

        How an instance shows what it has learned. Every driver prints `learned STORE ID16 HOST:PORT` when it first
        sees a peer in a store (the Silica driver's application asks its own peer for samples to find out). A peer named
        in a line `tick STORE: shuffle with ID8 at HOST:PORT` is also one that instance holds in that store (it dials
        only what its store holds). Both forms are read for every instance.
    gossip_run.py tokens-unit write FILE | check FILE
        The Silica unit `gossip_tokens` of the Silica driver's leaf: the sentinel's token for a peer that reads the
        system clock (tempus_sentinel, valid 1000 to 4000000000). lib/tempus_ids.silica has no such token.

The drivers must have been built: `make build` beside this file does that.
"""
import os
import re
import signal
import subprocess
import sys
import threading
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CLIENTS = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(CLIENTS, "python", "lib"))
sys.path.insert(0, os.path.join(CLIENTS, "python", "testing"))
import bees_tempus_certs as certs  # noqa: E402
import trial_ports  # noqa: E402
import bees_tempus_testing as testing  # noqa: E402  TEST ONLY: the test producer's key signs the example's tokens
from bees_tempus_codec import peer_id  # noqa: E402

CERTS = os.path.join(ROOT, "trials", "t5_tempus_tls", "certs")
KID = "k1"
VALID = (1000, 4000000000)
BASE = trial_ports.base("c7_tempus_gossip")
# the identity of each slot (a name of tools/bees_tempus_certs.py) and its port offset: slot 0 is the sentinel
SLOTS = ["sentinel", "node", "other", "x1", "x2"]
STORES = ["--store-edge", "8:4:500", "--store-bridge", "8:4:5000", "--store-sentinel", "8:4:1000"]
NETWORKS = {
    "python": ["python", "python", "python", "python"],
    "kotlin": ["kotlin", "kotlin", "kotlin", "kotlin"],
    "swift": ["swift", "swift", "swift", "swift"],
    "silica": ["silica", "silica", "silica", "silica"],
    "mixed": ["silica", "silica", "python", "kotlin", "swift"],
    "trio": ["swift", "python", "kotlin", "swift"],
}
SILICA_ENTRY = ["dangerous_gs", "dangerous_g1", "dangerous_g2", "dangerous_g3"]      # by slot: the values are compiled in
MIN_SECONDS = 6.0          # the least time a network runs, so that every instance's stores tick several times


def producer():
    return testing.fixture_key(0)


def token(name, typ):
    return testing.make_token(producer(), KID, certs.public_bytes(name), typ, *VALID)


def tokens_unit():
    return ('''// GENERATED by example_tempus_clients/gossip/gossip_run.py (`tokens-unit write`); do not edit. TEST ONLY: the token of the
// sentinel of the gossip examples, for a peer that reads the system clock: tempus_sentinel for the identity `sentinel`
// of tools/bees_tempus_certs.py, signed with the test producer key, valid %d to %d. Lower-case hex, read with
// tempus_ids@unhex.
module gossip_tokens;

export sentinel_hex/0;

fn sentinel_hex() -> string { "%s" }
''' % (VALID[0], VALID[1], token("sentinel", "tempus_sentinel").hex()))


class Instance:
    def __init__(self, slot, lang):
        self.slot, self.lang = slot, lang
        self.name = SLOTS[slot]
        self.typ = "tempus_sentinel" if slot == 0 else "tempus_edge"
        self.label = "s" if slot == 0 else "e%d" % slot
        self.port = BASE + slot
        self.addr = "127.0.0.1:%d" % self.port
        self.id16 = peer_id(certs.public_bytes(self.name))[:8].hex()
        self.lines = []
        self.learned = {}                # store -> set of id16, or of id8 from a line that names a shuffle's partner
        self.merged = {}                 # store -> shuffles this instance started that were answered and merged
        self.failed = {}                 # store -> shuffles this instance started that failed
        self.listening = threading.Event()
        self.proc = None

    def command(self, out_dir, everyone):
        """(argv, working directory)"""
        if self.lang == "silica":
            if self.slot >= len(SILICA_ENTRY):
                raise SystemExit("the Silica driver has no instance compiled for slot %d" % self.slot)
            leaf = os.path.join(CLIENTS, "silica", "driver")
            return [os.path.join(leaf, SILICA_ENTRY[self.slot])], leaf
        tok = os.path.join(out_dir, self.name + ".token")
        with open(tok, "w") as f:
            f.write(token(self.name, self.typ).hex() + "\n")
        pem = lambda n: os.path.join(CERTS, n + ".pem")  # noqa: E731
        opts = ["--cert", pem(self.name), "--key", os.path.join(CERTS, self.name + "-key.pem"), "--token", tok,
                "--addr", self.addr, "--producer-pub", testing._raw_public(producer()).hex(), "--kid", KID, "--skew", "10",
                "--timeout-ms", "3000"] + STORES + ["--join-retry-ms", "500:2000", "--whitelist-cert", pem(SLOTS[0])]
        if self.slot != 0:
            opts += ["--sentinel", "127.0.0.1:%d" % BASE]
        if self.lang == "python":
            for other in everyone:
                if other is not self:
                    opts += ["--trusted-cert", pem(other.name)]
            return [sys.executable, os.path.join(CLIENTS, "python", "driver", "tempus_peer.py"), "gossip"] + opts, HERE
        if self.lang == "kotlin":
            jar = os.path.join(CLIENTS, "kotlin", "build", "bees-tempus-client.jar")
            return [os.environ.get("JAVA", "java"), "-cp", jar, "bees.tempus.MainKt", "gossip"] + opts, HERE
        if self.lang == "swift":
            return [os.path.join(CLIENTS, "swift", ".build", "debug", "tempus-client"), "gossip"] + opts, HERE
        raise SystemExit("no driver for %r" % self.lang)

    def start(self, out_dir, everyone):
        argv, cwd = self.command(out_dir, everyone)
        if not os.path.exists(argv[0]) and os.sep in argv[0]:
            raise SystemExit("FAIL: %s is not built (make build)" % argv[0])
        self.proc = subprocess.Popen(argv, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors="replace")
        threading.Thread(target=self._read, daemon=True).start()

    def _read(self):
        for line in self.proc.stdout:
            line = line.rstrip("\n")
            self.lines.append(line)
            if "listening on" in line:
                self.listening.set()
            m = re.match(r"learned (tempus_\w+) ([0-9a-f]{16}) ", line) or re.match(r"tick (tempus_\w+): shuffle with ([0-9a-f]{8}) at ", line)
            if m:
                self.learned.setdefault(m.group(1), set()).add(m.group(2))
            m = re.match(r"tick (tempus_\w+): shuffle (merged|failed)$", line)
            if m:
                counts = self.merged if m.group(2) == "merged" else self.failed
                counts[m.group(1)] = counts.get(m.group(1), 0) + 1

    def knows(self, store, other):
        have = self.learned.get(store, ())
        return other.id16 in have or other.id16[:8] in have

    def stop(self):
        if self.proc is None or self.proc.poll() is not None:
            return
        self.proc.send_signal(signal.SIGTERM)
        try:
            self.proc.wait(5)
        except subprocess.TimeoutExpired:
            self.proc.kill()
            self.proc.wait()


def missing(everyone):
    """what is still to be learned: a list of (who, store, whom)"""
    out = []
    edges = [x for x in everyone if x.slot != 0]
    for who in everyone:
        for e in edges:
            if e is not who and not who.knows("tempus_edge", e):
                out.append((who, "tempus_edge", e))
        if who.slot != 0 and not who.knows("tempus_sentinel", everyone[0]):
            out.append((who, "tempus_sentinel", everyone[0]))
    return out


def idle(everyone):
    """the instances that have not yet merged a shuffle of their edge store"""
    return [x for x in everyone if not x.merged.get("tempus_edge")]


def run(name, timeout, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    everyone = [Instance(slot, lang) for slot, lang in enumerate(NETWORKS[name])]
    started = []
    began = time.monotonic()
    try:
        for x in everyone:
            x.start(out_dir, everyone)
            started.append(x)
            if x.slot == 0 and not x.listening.wait(20):
                break                                    # the check below says what is missing
            time.sleep(0.3)
        until = time.monotonic() + timeout
        while ((missing(everyone) or idle(everyone) or time.monotonic() < began + MIN_SECONDS) and time.monotonic() < until
               and all(x.proc.poll() is None for x in started)):
            time.sleep(0.2)
        # what the check says is what was seen up to here: a shuffle that fails because its partner was already
        # stopped is not the network's doing
        left, lazy = missing(everyone), idle(everyone)
        failures = [(x, sum(x.failed.values())) for x in everyone if x.failed]
        died = [x for x in started if x.proc.poll() is not None]
        known = {x.label: {store: [o.label for o in everyone if o is not x and x.knows(store, o)]
                           for store in ("tempus_edge", "tempus_sentinel")} for x in everyone}
    finally:
        for x in started:
            x.stop()
    time.sleep(0.2)
    for x in everyone:
        with open(os.path.join(out_dir, "%s.%s.out" % (name, x.label)), "w") as f:
            f.write("\n".join(x.lines) + "\n")
    lines = ["TEMPUS gossip example `%s`: %d instances on 127.0.0.1, one network; every edge was given the sentinel's address only"
             % (name, len(everyone))]
    for x in everyone:
        lines.append("  %-2s  %-15s  %-6s driver  identity %-8s  %s  %s" % (x.label, x.typ, x.lang, x.name, x.id16, x.addr))
    for x in everyone:
        def labels(store):
            return " ".join(sorted(known[x.label][store])) or "(nobody)"
        text = "%s learned of, in its edge store: %s" % (x.label, labels("tempus_edge"))
        if x.slot != 0:
            text += "; in its sentinel store: %s" % labels("tempus_sentinel")
        lines.append(text)
    edge_left = [m for m in left if m[1] == "tempus_edge"]
    sent_left = [m for m in left if m[1] == "tempus_sentinel"]

    def verdict(rest):
        return "yes" if not rest else "NO (" + ", ".join("%s has not learned of %s" % (a.label, b.label) for a, _, b in rest) + ")"
    lines.append("every instance learned of every edge: %s" % verdict(edge_left))
    lines.append("every edge learned of the sentinel: %s" % verdict(sent_left))
    lines.append("every instance merged a shuffle of its edge store that it started: %s"
                 % ("yes" if not lazy else "NO (" + ", ".join(x.label for x in lazy) + " did not)"))
    lines.append("no shuffle failed while all instances ran: %s"
                 % ("yes" if not failures else "NO (" + ", ".join("%s: %d" % (x.label, n) for x, n in failures) + ")"))
    lines.append("every instance ran until it was stopped: %s"
                 % ("yes" if not died else "NO (" + ", ".join(x.label for x in died) + " ended by itself)"))
    text = "\n".join(lines) + "\n"
    with open(os.path.join(out_dir, name + ".check"), "w") as f:
        f.write(text)
    sys.stdout.write(text)
    bad = bool(left or lazy or failures or died)
    if bad:
        for x in everyone:
            sys.stdout.write("---- the last lines of %s (%s)\n%s\n" % (x.label, x.lang, "\n".join(x.lines[-8:])))
    return 1 if bad else 0


def main(argv):
    if len(argv) == 4 and argv[1] == "tokens-unit" and argv[2] in ("write", "check"):
        if argv[2] == "write":
            with open(argv[3], "w") as f:
                f.write(tokens_unit())
            return 0
        same = os.path.exists(argv[3]) and open(argv[3]).read() == tokens_unit()
        print("the tokens unit is current" if same else "%s differs from what the tool writes: run `tokens-unit write`" % argv[3])
        return 0 if same else 1
    if len(argv) >= 3 and argv[1] == "run" and argv[2] in NETWORKS:
        timeout, out_dir, rest = 90.0, os.path.join(HERE, ".run"), argv[3:]
        while rest:
            if rest[0] == "--timeout" and len(rest) > 1:
                timeout, rest = float(rest[1]), rest[2:]
            elif rest[0] == "--out" and len(rest) > 1:
                out_dir, rest = rest[1], rest[2:]
            else:
                print(__doc__)
                return 2
        return run(argv[2], timeout, out_dir)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
