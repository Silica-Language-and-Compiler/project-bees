#!/usr/bin/env python3
"""TEST-ONLY TEMPUS identities for the networked trials (T5 on), as a Silica unit `tempus_ids`.

    bees_tempus_ids.py write OUT_FILE CERT_PREFIX    writes the unit; CERT_PREFIX is how the trial's programs reach the
                                                     certificates of tools/bees_tempus_certs.py from their working directory
    bees_tempus_ids.py check OUT_FILE CERT_PREFIX    fails when OUT_FILE is not what this tool writes now

Identities, by number, are those of tools/bees_tempus_certs.py in the order of NAMES: for each its private seed (keys that
belong to nobody: fixed seeds), public key, peer id, the SHA-512 of its certificate's DER, its certificate and key file
names, and five tokens signed with the test producer key of tools/bees_tempus_fixtures.py:
  1 tempus_edge, 2 tempus_bridge, 3 tempus_sentinel (kid k1, valid 1000..2000), 4 tempus_edge under the old kid k0,
  5 tempus_edge expired at 1400. The trial's clock value is 1500 and its skew 10. For the clients' trials (C2):
  6 tempus_edge valid 1000..3000, 7 tempus_edge not valid before 1800, 8 tempus_edge under kid k1 but signed with another
  key, 9 tempus_edge whose sub is another key, 10 tempus_edge valid 1000..1600, 11 tempus_sentinel valid 1000..3000,
  12 tempus_edge valid 1000..2500, 13 tempus_bridge valid 1000..3000, 14 tempus_edge valid 1000..4000000000 (for a node
  that is not a test node: its clock runs on from the trial's value, however long a loaded machine takes).
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bees_tempus_certs as certs  # noqa: E402
import bees_tempus_client as c  # noqa: E402
import bees_tempus_fixtures as fx  # noqa: E402
from cryptography import x509  # noqa: E402
from cryptography.hazmat.primitives import serialization  # noqa: E402

NAMES = sorted(certs.SEEDS, key=lambda n: certs.SEEDS[n])   # node, other, sentinel, bridge, then any later ones
TYPS = {1: "tempus_edge", 2: "tempus_bridge", 3: "tempus_sentinel"}


def tokens(pub):
    out = {v: c.make_token(fx.PRODUCER, fx.KID, pub, typ, 1000, 2000) for v, typ in TYPS.items()}
    out[4] = c.make_token(fx.OLD, "k0", pub, "tempus_edge", 1000, 2000)
    out[5] = c.make_token(fx.PRODUCER, fx.KID, pub, "tempus_edge", 1000, 1400)
    out[6] = c.make_token(fx.PRODUCER, fx.KID, pub, "tempus_edge", 1000, 3000)
    out[7] = c.make_token(fx.PRODUCER, fx.KID, pub, "tempus_edge", 1800, 2000)
    out[8] = c.make_token(fx.OLD, fx.KID, pub, "tempus_edge", 1000, 2000)
    out[9] = c.make_token(fx.PRODUCER, fx.KID, fx.OLD_PUB, "tempus_edge", 1000, 2000)
    out[10] = c.make_token(fx.PRODUCER, fx.KID, pub, "tempus_edge", 1000, 1600)
    out[11] = c.make_token(fx.PRODUCER, fx.KID, pub, "tempus_sentinel", 1000, 3000)
    out[12] = c.make_token(fx.PRODUCER, fx.KID, pub, "tempus_edge", 1000, 2500)
    out[13] = c.make_token(fx.PRODUCER, fx.KID, pub, "tempus_bridge", 1000, 3000)
    out[14] = c.make_token(fx.PRODUCER, fx.KID, pub, "tempus_edge", 1000, 4000000000)
    return out


def table(fn, values, kind="string"):
    lines = ["fn %s(i: int64) -> %s {" % (fn, kind), "    case i of {"]
    for i, v in enumerate(values):
        lines.append("        %d -> %s;" % (i, v if kind == "int64" else '"%s"' % v))
    lines += ["        _: int64 -> %s" % ("0" if kind == "int64" else '""'), "    }", "}"]
    return "\n".join(lines)


def silica(prefix):
    files = certs.files()
    seeds, pubs, ids, fps, toks = [], [], [], [], []
    for name in NAMES:
        first = certs.SEEDS[name]
        seed = bytes(range(first, first + 32))
        pub = certs.public_bytes(name)
        der = x509.load_pem_x509_certificate(files[name + ".pem"]).public_bytes(serialization.Encoding.DER)
        seeds.append(seed.hex())
        pubs.append(pub.hex())
        ids.append(c.peer_id(pub).hex())
        fps.append(hashlib.sha512(der).hexdigest())
        toks.append(tokens(pub))
    unhex = fx.silica().split("fn at(s: string")[1].split("\nfn name(")[0]
    head = '''// GENERATED by tools/bees_tempus_ids.py (`write`); do not edit. TEST ONLY: identities for the networked TEMPUS trials,
// from fixed seeds (keys that belong to nobody). Identity i is: %s.
// Byte strings are lower-case hex, read with unhex/1; fp_hex is used as it is (the whitelist holds hex).
// tok_hex(i, v): 1 tempus_edge, 2 tempus_bridge, 3 tempus_sentinel, 4 tempus_edge under the old kid k0, 5 tempus_edge expired,
// 6 tempus_edge to 3000, 7 tempus_edge not yet valid, 8 tempus_edge signed with another key, 9 tempus_edge with another
// key as sub, 10 tempus_edge to 1600, 11 tempus_sentinel to 3000, 12 tempus_edge to 2500, 13 tempus_bridge to 3000,
// 14 tempus_edge to 4000000000.
module tempus_ids;

export name/1;
export seed_hex/1;
export pub_hex/1;
export id_hex/1;
export fp_hex/1;
export certfile/1;
export keyfile/1;
export tok_hex/2;
export producer_pub_hex/0;
export kid/0;
export now/0;
export skew/0;
export unhex/1;

fn producer_pub_hex() -> string { "%s" }
fn kid() -> string { "%s" }
fn now() -> int64 { %d }
fn skew() -> int64 { %d }

fn at(s: string''' % (", ".join("%d %s" % (i, n) for i, n in enumerate(NAMES)), fx.PRODUCER_PUB.hex(), fx.KID, fx.NOW, fx.SKEW)
    parts = [head + unhex.rstrip() + "\n", table("name", NAMES), table("seed_hex", seeds), table("pub_hex", pubs),
             table("id_hex", ids), table("fp_hex", fps), table("certfile", [prefix + n + ".pem" for n in NAMES]),
             table("keyfile", [prefix + n + "-key.pem" for n in NAMES])]
    for v in range(1, 15):
        parts.append(table("tok%d" % v, [t[v].hex() for t in toks]))
    parts.append("fn tok_hex(i: int64, v: int64) -> string {\n    case v of { 1 -> tok1(i); 2 -> tok2(i); 3 -> tok3(i); 4 -> tok4(i); 5 -> tok5(i); 6 -> tok6(i); 7 -> tok7(i); 8 -> tok8(i); 9 -> tok9(i); 10 -> tok10(i); 11 -> tok11(i); 12 -> tok12(i); 13 -> tok13(i); 14 -> tok14(i); _: int64 -> \"\" }\n}")
    return "\n".join(parts) + "\n"


def main(argv):
    if len(argv) == 4 and argv[1] == "write":
        os.makedirs(os.path.dirname(os.path.abspath(argv[2])), exist_ok=True)
        with open(argv[2], "w") as f:
            f.write(silica(argv[3]))
        return 0
    if len(argv) == 4 and argv[1] == "check":
        same = os.path.exists(argv[2]) and open(argv[2]).read() == silica(argv[3])
        print("identities are current" if same else "%s differs from what the tool writes: run `write`" % argv[2])
        return 0 if same else 1
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
