#!/usr/bin/env python3
"""bees_edge_gen: write a program's dangerous_ root unit from the BEES edge section (M2).

SD-17 (still open on silica-999936): a worker behaviour must be in the same unit as its
spawn_dangerous site, so the edge's Silica text cannot be a library. This tool is the build step
S4 anticipated: it writes

    use bees_reporter; use bees_atoms; use dangerous_bees_tcp;   (plus any `use` lines of the role)
    module <name>;
    <src/shim/bees_tcp_edge.part>
    <role files, in order: the program's own code>

    bees_edge_gen.py NAME OUT_FILE ROLE_FILE...
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PART = os.path.join(HERE, "..", "src", "shim", "bees_tcp_edge.part")


def main(argv):
    if len(argv) < 4:
        print(__doc__)
        return 2
    name, out, roles = argv[1], argv[2], argv[3:]
    if not name.startswith("dangerous_"):
        print("error: the root unit of a program that uses the native edge must be named dangerous_* (E4020)")
        return 1
    text = "// Generated by tools/bees_edge_gen.py from src/shim/bees_tcp_edge.part and %s. Do not edit.\n" % " ".join(os.path.basename(r) for r in roles)
    text += "use bees_reporter;\nuse bees_atoms;\nuse dangerous_bees_tcp;\n"
    text += "module %s;\n\n" % name
    text += open(PART).read()
    for r in roles:
        text += "\n" + open(r).read()
    with open(out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
