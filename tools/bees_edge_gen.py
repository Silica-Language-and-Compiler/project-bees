#!/usr/bin/env python3
"""bees_edge_gen: write a program's dangerous_ root unit from the BEES carrier edge and the program's role files.

The carrier is the language's (:tcp) carrier (transport design 6.2, 6.3), a library FFI worker of the Silica stdlib
(dangerous_tcp_carrier). A program that depends on it is a dangerous_ program (FFI wrapper specification 3.1), so
its root unit carries the prefix; this tool writes that unit:

    use bees_reporter; use bees_atoms; use carrier; use wireframe; use dangerous_sockets; use dangerous_tcp_carrier;
    (plus any --use UNIT lines)
    module <name>;
    <src/shim/bees_tcp_edge.part>        carrier_new(): one unopened (:tcp) carrier
    <src/shim/bees_node_edge.part>       with --use dangerous_bees_net: net_launch, net_start, net_raw_writer, net_send_raw
    <role files, in order: the program's own code>

    bees_edge_gen.py NAME OUT_FILE [--use UNIT]... ROLE_FILE...

`--use UNIT` adds `use UNIT;` to the unit's header (dangerous_bees_net, bees_peers, ... for a node program). The leaf's lib/
must link the stdlib units carrier, wireframe, wire_etf, dangerous_sockets and dangerous_tcp_carrier (tools/silica.mk,
SILICA_STDLIB) and its dangerous_exposure_source must hold the socket wrappers' sidecar and archive (native/Makefile).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PART = os.path.join(HERE, "..", "src", "shim", "bees_tcp_edge.part")
# A node program (one that uses dangerous_bees_net) also gets the node edge: the spawns of dangerous_bees_net's behaviours and
# the casts to them, which E4042 keeps out of any non-worker caller of a dangerous_ unit (bees_node_edge.part's header).
NODE_PART = os.path.join(HERE, "..", "src", "shim", "bees_node_edge.part")
NODE_UNIT = "dangerous_bees_net"
NODE_USES = ["bees_ingress", "bees_peers"]
HEADER_USES = ["bees_reporter", "bees_atoms", "carrier", "wireframe", "dangerous_sockets", "dangerous_tcp_carrier"]


def main(argv):
    if len(argv) < 4:
        print(__doc__)
        return 2
    name, out, rest = argv[1], argv[2], argv[3:]
    uses, roles = [], []
    while rest:
        if rest[0] == "--use" and len(rest) > 1:
            uses.append(rest[1])
            rest = rest[2:]
        else:
            roles.append(rest[0])
            rest = rest[1:]
    if not roles:
        print(__doc__)
        return 2
    if not name.startswith("dangerous_"):
        print("error: the root unit of a program that uses the (:tcp) carrier must be named dangerous_* (E4020, FFI wrapper spec 3.1)")
        return 1
    text = "// Generated by tools/bees_edge_gen.py from src/shim/bees_tcp_edge.part and %s. Do not edit.\n" % " ".join(os.path.basename(r) for r in roles)
    text += "".join("use %s;\n" % u for u in HEADER_USES)
    node = NODE_UNIT in uses
    if node:
        uses = uses + [u for u in NODE_USES if u not in uses]
    text += "".join("use %s;\n" % u for u in uses if u not in HEADER_USES)
    text += "module %s;\n\n" % name
    text += open(PART).read()
    if node:
        text += open(NODE_PART).read()
    for r in roles:
        text += "\n" + open(r).read()
    with open(out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
